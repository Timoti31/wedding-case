function contactsBlock(me, ctx) {
  const list = Object.entries(CONTACTS[me] || {}).filter(([k]) => ctx.usernames?.[k]);
  if (!list.length) return '';
  return '\n\nКОНТАКТЫ. Ты можешь дать собеседникам Telegram этих людей. Чтобы дать контакт, напиши в тексте код в фигурных скобках, сервер заменит его на настоящий ник. Сам ники не пиши.\n'
    + list.map(([k, d]) => `${d}: {{${k}}}`).join('\n')
    + `\nПример: «костя, друг димы: {{${list[0][0]}}}».\nНомера телефонов никогда не даешь и не выдумываешь, все общаются только в Telegram. Контактов других людей у тебя нет: «не знаю, у меня его нет».`;
}

function build({ extra = '', card, stage, trust, ctx, me }) {
  card += contactsBlock(me, ctx);
  const state = [
    `Сейчас этап ${stage} из 5.`,
    `Твое доверие к собеседникам: ${trust} из 10.`,
    ctx.given?.length ? `Ты уже выдал: ${ctx.given.join(', ')}. Повторно не выдавай.` : '',
  ].filter(Boolean).join('\n');
  return COMMON.replace('{EXTRA}', extra) + '\n\n' + card + '\n\nТЕКУЩЕЕ СОСТОЯНИЕ\n' + state;
}

