function stageRows(rows, stage) {
  return Object.entries(rows)
    .filter(([s]) => Number(s) <= stage)
    .map(([s, t]) => `Этап ${s}: ${t}`)
    .join('\n');
}

function build({ extra = '', card, stage, trust, ctx }) {
  const state = [
    `Сейчас этап ${stage} из 5.`,
    `Твое доверие к собеседникам: ${trust} из 10.`,
    ctx.given?.length ? `Ты уже выдал: ${ctx.given.join(', ')}. Повторно не выдавай.` : '',
  ].filter(Boolean).join('\n');
  return COMMON.replace('{EXTRA}', extra) + '\n\n' + card + '\n\nТЕКУЩЕЕ СОСТОЯНИЕ\n' + state;
}

